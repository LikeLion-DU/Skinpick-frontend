/// 게이트 임계값을 한 파일에 모은다.
///
/// 실기기에서 촬영 UX 를 보면 거의 반드시 손대게 되는 값들이다. 판정 코드 안에
/// 흩어져 있으면 튜닝할 때마다 로직을 읽어야 한다. (PRD §9.5 기준값)
class FaceGateConfig {
  const FaceGateConfig._();

  /// 얼굴 바운딩 박스 높이가 프레임 높이의 몇 배 이상이어야 하는가.
  /// 이 값이 낮으면 멀리서 찍은 사진이 통과하고, OpenAI 에 올라가는 얼굴의
  /// 실효 해상도가 떨어져 홍조·트러블 판정 근거가 사라진다.
  ///
  /// **실기기(갤럭시 S25) 측정으로 0.40 에서 0.34 로 낮췄다.** 팔을 자연스럽게
  /// 뻗어 정면을 잡으면 38.5% 가 나오는데, 그 자세에서 "얼굴이 너무 작아요"로
  /// 계속 막혔다. 측면은 얼굴이 더 좁게 잡혀 여유가 한 겹 더 필요하다.
  ///
  /// 해상도 걱정은 크롭이 받아낸다 — 업로드하는 것은 프레임 전체가 아니라
  /// 얼굴 박스에 여백을 붙여 잘라낸 이미지라, 34% 여도 잘린 뒤에는 그게 전부다.
  static const double minFaceHeightRatio = 0.34;

  /// 얼굴이 너무 커서 이마·턱이 프레임을 넘어가기 시작하는 지점.
  ///
  /// 하한과 달리 이 값은 여유를 크게 둔다 — 가까이 올수록 피부 정보는 늘어나므로
  /// 막을 이유가 "얼굴이 다 안 들어온다" 하나뿐이고, 그건 [outOfFrameSlackRatio]
  /// 가 이미 잡는다. 여기서 좁게 잡으면 정상 촬영이 막힌다.
  static const double maxFaceHeightRatio = 0.65;

  /// 얼굴 중심이 프레임 중심에서 벗어나도 되는 정도 (프레임 가로·세로 대비).
  ///
  /// **프리뷰는 프레임을 `BoxFit.cover` 로 잘라 보여준다.** 화면에서 보이는 중앙과
  /// 프레임의 중앙이 기기마다 조금씩 어긋나므로 좁게 잡으면 안 된다. 가이드 타원의
  /// 세로 중심도 화면의 47% 라 정확히 중앙이 아니다. 0.15 는 그 오차를 다 덮는다.
  static const double centerToleranceX = 0.15;
  static const double centerToleranceY = 0.15;

  /// 얼굴 박스가 프레임 밖으로 이만큼(프레임 크기 대비)까지 나가는 것은 봐준다.
  /// ML Kit 박스는 프레임마다 몇 픽셀씩 떨린다 — 0 으로 두면 가장자리에서 판정이
  /// 진동한다.
  static const double outOfFrameSlackRatio = 0.02;

  /// 눈 뜸 확률 하한 (0~1). **0 으로 두면 눈 검사를 끈다.**
  ///
  /// 확실히 감은 경우만 막는다. 측면 단계에서는 먼 쪽 눈이 가려져 확률이 낮게
  /// 나오므로 판정은 **양쪽 중 큰 값**으로 한다 — 둘 다 보고 막으면 측면에서
  /// 상시 걸린다.
  ///
  /// 이 값은 **촬영 게이트 전용이다.** 눈 뜸 확률로 피부 상태를 추정하지 않는다
  /// (PRD §9.5 — 게이트와 크롭까지가 전부다).
  static const double eyeOpenThreshold = 0.35;

  /// 정면 판정 허용 범위(도). yaw · roll 양쪽에 적용한다.
  static const double frontMaxYaw = 15.0;
  static const double frontMaxRoll = 15.0;

  /// 측면 판정에서 "충분히 돌렸다"고 보는 최소 yaw(도).
  /// 이 값과 [frontMaxYaw] 사이는 "조금 더 돌려주세요" 구간이다.
  static const double sideMinYaw = 25.0;

  /// 얼굴 영역 평균 휘도 하한 (0~255).
  ///
  /// 발표장 조명은 천장에서 내리쬐어 눈 아래·코 밑에 그림자를 만든다.
  /// 이 값을 올리면 시연장에서 촬영 버튼이 안 눌릴 위험이 커진다.
  static const int minLuminance = 60;

  /// 크롭·오버레이에 붙이는 여백 비율. 딱 맞게 자르면 이마와 턱이 잘리는데,
  /// 그 두 곳이 유분·트러블 판정에서 정보량이 가장 많다.
  static const double faceMarginRatio = 0.20;

  /// ML Kit 의 `headEulerAngleY` 부호가 "사용자 기준 왼쪽"과 같은 방향인지.
  ///
  /// 부호는 카메라 파이프라인의 미러 처리에 따라 뒤집히는 **환경 특성**이다.
  /// 측정 이력:
  /// - 2026-08-12 에뮬레이터+웹캠: 본인 왼쪽으로 돌리면 yaw 음수 → -1.0
  /// - 2026-08-15 에뮬레이터+맥북 내장캠(webcam1): 지시 방향과 판정이 반대로
  ///   나온다는 QA 리포트 → 1.0 으로 반전 (당시와 웹캠 장치가 다르다)
  ///
  /// 실기기에서 LEFT 를 요구했는데 오른쪽으로 돌려야 통과하면 이 상수 하나만
  /// 뒤집는다. 좌우가 통째로 뒤집힌다.
  static const double userLeftYawSign = 1.0;

  /// 심하게 고개가 꺾인 상태를 거부할지. 촬영 실패율을 올리는 조건이라
  /// 기본은 꺼 둔다 (지시서 §15). 실기기 UX 를 본 뒤에만 켠다.
  static const bool enablePitchCheck = false;
  static const double maxPitch = 20.0;

  /// 실시간 프레임 분석 최소 간격. 매 프레임 ML Kit 을 호출하면 프리뷰가 끊긴다.
  static const Duration analysisInterval = Duration(milliseconds: 300);

  /// 이 횟수만큼 **연속으로** 통과해야 촬영 준비 완료로 본다.
  /// 셔터 활성화와 자동 촬영이 같은 기준을 쓴다.
  ///
  /// 한 프레임만 보고 켜면 고개를 돌리다 스쳐 지나가는 순간에 버튼이 켜지고
  /// 셔터가 눌려서, 사용자는 자세를 잡기도 전에 다음 단계로 넘어가 버린다.
  /// [analysisInterval] 이 300ms 이므로 3회면 약 0.9초 유지다.
  static const int stableFrames = 3;

  /// 오버레이 얼굴 박스의 프레임 간 보간 비율 (0~1, 클수록 빠르게 따라간다).
  ///
  /// ML Kit 박스는 300ms 마다 몇 픽셀씩 튄다. 그대로 그리면 사각형이 얼굴 위에서
  /// 떨려서 화면이 고장 난 것처럼 보인다.
  ///
  /// **에뮬레이터 측정으로 0.35 에서 0.5 로 올렸다(2026-08-17).** 얼굴을 화면
  /// 가장자리에서 중앙으로 빠르게 옮기면(중심 오프셋 0.48 → -0.04) 0.35 에서는
  /// 1초 뒤에도 박스가 0.07 에 남아 얼굴을 눈에 띄게 따라다녔다. 판정은 원본
  /// 값으로 하므로 이 상수는 그리기에만 영향을 준다.
  static const double faceBoxSmoothing = 0.5;

  // 우회 임계값(구 forceCaptureAfterFailures)은 제거했다. 게이트를 통과하지 못한
  // 이미지는 어떤 경로로도 서버에 올라가지 않는다. 상수를 남겨두면 우회가
  // 다시 붙는 자리가 된다.
}
